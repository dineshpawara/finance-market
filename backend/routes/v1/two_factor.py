"""
Two-Factor Authentication (2FA) Routes (V1)
===========================================
Provides REST endpoints for Google Authenticator setup, QR code generation,
first-time confirmation, status inspection, and deactivation.
"""

from fastapi import APIRouter, Depends, Request, Response, status
from sqlalchemy.orm import Session

from database.session import get_db
from models.user import User
from core.security import get_current_user
from core.rate_limiter import limiter
from repository.user_repository import UserRepository
from repository.totp_repository import TOTPRepository
from services.auth_service import AuthService
from services.totp_service import TOTPService
from controller.totp_controller import TwoFactorController
from schemas.two_factor import (
    TwoFactorSetupResponse,
    TwoFactorVerifySetupRequest,
    TwoFactorVerifySetupResponse,
    TwoFactorStatusResponse,
    TwoFactorDisableRequest,
)

twoFactorRoute = APIRouter(prefix="/2fa", tags=["Two-Factor Authentication V1"])


def get_two_factor_controller(db: Session = Depends(get_db)) -> TwoFactorController:
    """Dependency factory assembling the repository -> service -> controller chain."""
    user_repo = UserRepository(db)
    totp_repo = TOTPRepository(db)
    auth_service = AuthService(user_repo=user_repo, totp_repo=totp_repo)
    totp_service = TOTPService(totp_repo=totp_repo, user_repo=user_repo)
    return TwoFactorController(totp_service=totp_service, auth_service=auth_service)


@twoFactorRoute.post(
    "/setup",
    response_model=TwoFactorSetupResponse,
    status_code=status.HTTP_200_OK,
    summary="Generate Google Authenticator TOTP Secret and QR Code",
    description="Generates a cryptographically strong Base32 secret seed, encrypts it at rest, and returns provisioning URI with Base64 QR code.",
)
@limiter.limit("5/minute")
def setup_2fa(
    request: Request,
    response: Response,
    current_user: User = Depends(get_current_user),
    controller: TwoFactorController = Depends(get_two_factor_controller),
) -> TwoFactorSetupResponse:
    """
    Clean Architecture flow:
    Route -> Controller -> TOTPService (Fernet Encryption & QR Generation) -> Schema
    """
    return controller.setup(user=current_user)


@twoFactorRoute.post(
    "/verify-setup",
    response_model=TwoFactorVerifySetupResponse,
    status_code=status.HTTP_200_OK,
    summary="Confirm Initial Passcode and Activate 2FA",
    description="Validates the user's first 6-digit passcode generated by Google Authenticator app, transitioning status to ACTIVE.",
)
@limiter.limit("5/minute")
def verify_setup_2fa(
    request: Request,
    response: Response,
    data: TwoFactorVerifySetupRequest,
    current_user: User = Depends(get_current_user),
    controller: TwoFactorController = Depends(get_two_factor_controller),
) -> TwoFactorVerifySetupResponse:
    """
    Confirms initial TOTP registration and activates 2FA.
    """
    return controller.verify_setup(user=current_user, data=data)


@twoFactorRoute.get(
    "/status",
    response_model=TwoFactorStatusResponse,
    status_code=status.HTTP_200_OK,
    summary="Query Current 2FA Status",
    description="Returns whether Two-Factor Authentication is currently enforced for the logged-in user.",
)
def get_2fa_status(
    current_user: User = Depends(get_current_user),
    controller: TwoFactorController = Depends(get_two_factor_controller),
) -> TwoFactorStatusResponse:
    """
    Inspects 2FA status for the authenticated user.
    """
    return controller.get_status(user=current_user)


@twoFactorRoute.post(
    "/disable",
    status_code=status.HTTP_200_OK,
    summary="Disable Two-Factor Authentication",
    description="Deactivates 2FA protection upon dual-verification of account password and current 6-digit TOTP code.",
)
@limiter.limit("5/minute")
def disable_2fa(
    request: Request,
    response: Response,
    data: TwoFactorDisableRequest,
    current_user: User = Depends(get_current_user),
    controller: TwoFactorController = Depends(get_two_factor_controller),
) -> dict:
    """
    Disables 2FA with dual-factor verification.
    """
    return controller.disable(user=current_user, data=data)
