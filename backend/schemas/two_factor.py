"""
Two-Factor Authentication (2FA / TOTP) Schemas
==============================================
Pydantic V2 validation models for Google Authenticator TOTP setup,
verification, challenge handling, and status queries.
"""

from typing import Optional
from pydantic import BaseModel, Field, ConfigDict


class TwoFactorSetupResponse(BaseModel):
    """
    Response returned when initializing 2FA setup for Google Authenticator.
    Provides secret seed, provisioning URI, and high-resolution base64 QR code.
    """

    secret_key: str = Field(..., description="Base32 secret key for manual entry into Google Authenticator")
    otpauth_url: str = Field(..., description="Standard otpauth:// provisioning URI")
    qr_code_base64: str = Field(..., description="Data URI formatted Base64 PNG image for QR scanning")
    status: str = Field(default="PENDING", description="Enrollment status: PENDING")

    model_config = ConfigDict(from_attributes=True)


class TwoFactorVerifySetupRequest(BaseModel):
    """
    Payload to confirm initial 2FA setup by validating the first 6-digit passcode.
    """

    code: str = Field(
        ...,
        min_length=6,
        max_length=8,
        description="6-digit passcode generated by Google Authenticator app",
    )


class TwoFactorVerifySetupResponse(BaseModel):
    """
    Confirmation response after successfully activating 2FA.
    """

    success: bool = Field(default=True, description="Confirmation flag")
    message: str = Field(..., description="Status description")
    is_enabled: bool = Field(default=True, description="Indicates 2FA is active")


class TwoFactorVerifyLoginRequest(BaseModel):
    """
    Payload for Stage-2 login challenge verification.
    Submits the temporary pre-auth session token alongside the 6-digit TOTP code.
    """

    temp_token: str = Field(
        ...,
        min_length=1,
        description="Short-lived pre-auth JWT token obtained from Stage-1 /login",
    )
    code: str = Field(
        ...,
        min_length=6,
        max_length=8,
        description="6-digit passcode generated by Google Authenticator app",
    )


class TwoFactorStatusResponse(BaseModel):
    """
    Returns current Two-Factor Authentication state for the user.
    """

    is_enabled: bool = Field(..., description="Whether 2FA is currently active and enforced")
    status: str = Field(..., description="Status string: ACTIVE, PENDING, or DISABLED")
    enabled_at: Optional[str] = Field(default=None, description="Timestamp when 2FA was enabled (ISO format)")

    model_config = ConfigDict(from_attributes=True)


class TwoFactorDisableRequest(BaseModel):
    """
    Dual-credential authorization payload required to disable 2FA security.
    """

    password: str = Field(..., min_length=1, description="Current account password")
    code: str = Field(..., min_length=6, max_length=8, description="Current 6-digit Google Authenticator code")
